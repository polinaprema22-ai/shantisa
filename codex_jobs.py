def refs_for(sid):
    r = json.load(open(os.path.join(ROOT, "raw/codex_refs.json")))[sid]
    return [os.path.join(ROOT, p) for p in (r["maryana"][:3] + r["danya"][:1])]

def job(sid, view):
    kind, title, desc = ITEMS[sid]
    refs = refs_for(sid)
    n = len(refs)
    if view in ("model", "kidmodel"):
        style = STYLE.get(kind + "_model") if kind != "kids" else None
    else:
        style = STYLE["product"]
    head = ("Карточка товара для интернет-магазина. Картинки 1–%d — фотографии настоящей вещи: главный и самый точный референс, "
            "анализируй их вместе." % n)
    if style:
        head += " Последняя картинка (%d) — только образец стиля съёмки%s; вещь с неё НЕ копировать." % (n + 1, " и внешности модели" if view == "model" else "")
    prompt = "%s\nВещь: «%s» — %s.\n%s%s\n%s" % (head, title, desc, VIEW[view], STYLING[kind] if view == "model" else "", RULES)
    return {"id": sid, "view": view, "out": os.path.join(ROOT, "raw/codex", sid, view + ".png"),
            "refs": refs + ([style] if style else []), "prompt": prompt}

def build():
    jobs = []
    for sid, (kind, _, _) in ITEMS.items():          # проход 1: обложка и перед
        jobs.append(job(sid, "front"))
        jobs.append(job(sid, "back" if kind == "kids" else "model"))
    for sid, (kind, _, _) in ITEMS.items():          # проход 2: остальные ракурсы
        for v in (["side", "34", "kidmodel"] if kind == "kids" else ["back", "side", "34"]):
            jobs.append(job(sid, v))
    json.dump(jobs, open(os.path.join(ROOT, "raw/codex/jobs.json"), "w"), ensure_ascii=False, indent=1)
    print(len(jobs), "заданий")

def run(limit):
    jobs = json.load(open(os.path.join(ROOT, "raw/codex/jobs.json")))
    done = 0
    for j in jobs:
        if os.path.exists(j["out"]):
            continue
        if done >= limit:
            break
        t = time.time()
        r = subprocess.run([DRAW, j["prompt"], j["out"]] + j["refs"], capture_output=True, text=True, errors="replace",
                           env=dict(os.environ, LANG="en_US.UTF-8", LC_ALL="en_US.UTF-8"))
        line = (r.stdout.strip().splitlines() or [""])[-1]
        rec = {"id": j["id"], "view": j["view"], "sec": round(time.time() - t), "res": line[:400], "at": time.strftime("%H:%M:%S")}
        open(os.path.join(ROOT, "raw/codex/progress.jsonl"), "a").write(json.dumps(rec, ensure_ascii=False) + "\n")
        print(json.dumps(rec, ensure_ascii=False), flush=True)
        done += 1
        if "лимит" in line:
            print("СТОП: лимит подписки", flush=True); break

if __name__ == "__main__":
    if sys.argv[1] == "build": build()
    else: run(int(sys.argv[2]) if len(sys.argv) > 2 else 10**6)
